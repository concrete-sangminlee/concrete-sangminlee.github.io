export function detectLang(saved) {
    if (saved === 'ko' || saved === 'en') return saved;
    const langs = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
    return langs.some(l => /^ko\b/i.test(l)) ? 'ko' : 'en';
}
